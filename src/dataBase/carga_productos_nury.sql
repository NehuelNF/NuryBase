-- 3) Receta trivial (cantidad = 1) que une cada producto con su propio ingrediente,
--    igual que hicimos con la Coca-Cola 591cc: así la venta descuenta stock sin necesitar
--    una receta compuesta.
INSERT INTO recetas (producto_id, ingrediente_id, cantidad_necesaria, unidad_id)
SELECT p.id, i.id, 1, u.id
FROM productos p
JOIN ingredientes i ON i.nombre = p.nombre
CROSS JOIN (SELECT id FROM unidades_medida WHERE abreviatura = 'un') u
ON CONFLICT (producto_id, ingrediente_id) DO NOTHING;

