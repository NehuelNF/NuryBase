-- Detener la transaccion si el SKU o el codigo de barras ya pertenece a otro nombre.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM public.productos p JOIN _productos_limpios_2026 s ON p.sku = s.sku
        WHERE p.nombre <> s.nombre
    ) THEN RAISE EXCEPTION 'Hay SKU asociados a otro producto'; END IF;
    IF EXISTS (
        SELECT 1 FROM public.productos p JOIN _productos_limpios_2026 s ON p.codigo_barras = s.codigo_barras
        WHERE p.nombre <> s.nombre
    ) THEN RAISE EXCEPTION 'Hay codigos de barras asociados a otro producto'; END IF;
    IF EXISTS (
        SELECT 1 FROM public.productos p JOIN _productos_limpios_2026 s ON p.nombre = s.nombre
        WHERE p.sku IS NOT NULL AND p.sku <> s.sku
    ) THEN RAISE EXCEPTION 'Hay nombres existentes con otro SKU'; END IF;
END $$;

